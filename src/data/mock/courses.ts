const sectionSet = (kinds: CourseSectionKind[]): CourseSection[] =>
  kinds.map((kind, order) => {
    const [en, ar, descriptionEn, descriptionAr] = sectionCopy[kind];
    return {
      id: kind,
      kind,
      title: text(en, ar),
      description: text(descriptionEn, descriptionAr),
      order,
    };
  });
