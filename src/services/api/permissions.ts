export const capabilitiesFor = (permissions: string[]): Capability[] => {
  const capabilities = (
    Object.entries(capabilityMap) as [Capability, string[]][]
  )
    .filter(([, names]) => names.some((name) => permissions.includes(name)))
    .map(([capability]) => capability);
  if (permissions.some((name) => name.startsWith("assets."))) {
    if (!capabilities.includes("assets.manage"))
      capabilities.push("assets.manage");
    if (!capabilities.includes("admin.access"))
      capabilities.push("admin.access");
  }
  // Navigation grouping only; the backend authorizes every request and resource scope.
  if(permissions.some(name=>/^(analytics|search|audit|governance_versions|system|security|operations)\./.test(name))){
    if(!capabilities.includes("operations.manage"))capabilities.push("operations.manage");
    if(!capabilities.includes("admin.access"))capabilities.push("admin.access");
  }
  if(permissions.some(name=>/^(mentorship|recruitment|member_profiles)\./.test(name))){if(!capabilities.includes("membership.manage"))capabilities.push("membership.manage");if(!capabilities.includes("admin.access"))capabilities.push("admin.access");}
  return capabilities;
};
